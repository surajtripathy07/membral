// A real HTTP server always populates content-length for a non-chunked
// body; NextRequest constructed directly in tests does not, so every
// helper below computes and sets it explicitly — otherwise every test
// would trip the round-3 "content-length required" guard (item 2).
function jsonRequest(body: unknown, opts: { url?: string; contentLength?: string | null } = {}): NextRequest {
  const text = JSON.stringify(body);
  const headers: Record<string, string> = { "content-type": "application/json" };
  if (opts.contentLength !== null) {
    headers["content-length"] = opts.contentLength ?? String(new TextEncoder().encode(text).byteLength);
  }
  return new NextRequest(opts.url ?? "http://localhost:3000/api/import/upload", {
    method: "POST",
    headers,
    body: text,
  });
}

async function multipartRequest(
  fileContent: Uint8Array,
  filename: string,
  opts: { url?: string; contentLength?: string | null } = {},
): Promise<NextRequest> {
  const form = new FormData();
  form.set("file", new File([fileContent as BlobPart], filename));
  // FormData bodies get their multipart boundary/content-type generated by
  // the fetch implementation itself — materialize a throwaway Request to
  // read the real serialized bytes (and thus a real content-length) rather
  // than guessing at the encoding.
  const proto = new Request("http://localhost/", { method: "POST", body: form });
  const serialized = new Uint8Array(await proto.arrayBuffer());
  const headers: Record<string, string> = { "content-type": proto.headers.get("content-type") ?? "" };
  if (opts.contentLength !== null) {
    headers["content-length"] = opts.contentLength ?? String(serialized.byteLength);
  }
  return new NextRequest(opts.url ?? "http://localhost:3000/api/import/upload", {
    method: "POST",
    headers,
    body: serialized,
  });
}

