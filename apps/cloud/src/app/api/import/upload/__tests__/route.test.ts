      const inflateCall = vi.mocked(inflateSync).mock.calls.at(-1);
      expect(inflateCall).toBeTruthy();
      const opts = inflateCall?.[1] as { out?: Uint8Array } | undefined;
      expect(opts?.out).toBeInstanceOf(Uint8Array);
      expect(opts?.out?.length).toBe(512 * 1024 * 1024); // MAX_ENTRY_UNCOMPRESSED_BYTES
