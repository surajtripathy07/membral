      // bytes — this is exactly the shape that used to reach
      // `inflateSync(compressed, undefined)` (no bound at all).
      let headerOffset = -1;
      for (let i = 0; i + 4 <= zipped.length; i++) {
        if (zipped[i] === 0x50 && zipped[i + 1] === 0x4b && zipped[i + 2] === 0x03 && zipped[i + 3] === 0x04) {
          headerOffset = i;
          break;
        }
      }
      expect(headerOffset).toBeGreaterThanOrEqual(0);
      const view = new DataView(zipped.buffer, zipped.byteOffset, zipped.byteLength);
      view.setUint32(headerOffset + 22, 0, true); // uncompressedSize -> 0 (lying)

      // Force the ZIP64/raw-scan fallback path (same trick as the H8 tests).
      vi.mocked(unzipSync).mockImplementationOnce(() => ({}));

      const res = await POST(await multipartRequest(zipped, "export.zip"));
