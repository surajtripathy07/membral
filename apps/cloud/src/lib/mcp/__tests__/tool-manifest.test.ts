// Drift guard for the offline tool list `membral mcp` answers from when no
// stack is reachable (packages/core/src/mcp-tool-manifest.ts). The manifest
// is the unscoped server's initialize `instructions` + tools/list, read over
// a real MCP round trip. If this test fails, regenerate the file:
//   UPDATE_MCP_MANIFEST=1 npx vitest run src/lib/mcp/__tests__/tool-manifest.test.ts
// (from apps/cloud) and commit the result.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MCP_SERVER_INFO, MCP_TOOL_MANIFEST, MCP_TOOL_MANIFEST_INSTRUCTIONS } from "@membral/core";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { describe, expect, it, vi } from "vitest";

vi.mock("@supabase/supabase-js", () => ({ createClient: vi.fn(() => ({ from: vi.fn() })) }));

import { createCloudMcpServer } from "../server";

/** Recursively sort object keys so the snapshot is deterministic. */
function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v as Record<string, unknown>)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([k, x]) => [k, sortKeys(x)]),
    );
  }
  return v;
}

async function live() {
  const server = createCloudMcpServer("user-123", null, null);
  const client = new Client({ name: "test", version: "0.0.0" });
  const [ct, st] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(st), client.connect(ct)]);
  const { tools } = await client.listTools();
  const info = client.getServerVersion();
  const manifest = tools
    .map((t) => sortKeys({ name: t.name, description: t.description ?? "", inputSchema: t.inputSchema }))
    .sort((a, b) => ((a as { name: string }).name < (b as { name: string }).name ? -1 : 1));
  return { manifest, instructions: client.getInstructions() ?? "", info };
}

describe("offline MCP tool manifest", () => {
  it("matches the cloud registry (names, descriptions, input schemas, instructions)", async () => {
    const { manifest, instructions, info } = await live();
    if (process.env.UPDATE_MCP_MANIFEST === "1") {
      const out = fileURLToPath(new URL("../../../../../../packages/core/src/mcp-tool-manifest.ts", import.meta.url));
      writeFileSync(
        out,
        `// GENERATED by apps/cloud/src/lib/mcp/__tests__/tool-manifest.test.ts (UPDATE_MCP_MANIFEST=1).\n// Do not edit by hand: a drift test fails when this differs from the cloud registry.\n// Offline tools/list for \`membral mcp\` when no Membral stack is reachable.\nexport const MCP_SERVER_INFO = ${JSON.stringify({ name: info?.name, version: info?.version })} as const;\n\nexport const MCP_TOOL_MANIFEST_INSTRUCTIONS = ${JSON.stringify(instructions)};\n\nexport const MCP_TOOL_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`,
      );
      return;
    }
    expect(MCP_TOOL_MANIFEST).toEqual(manifest);
    expect(MCP_TOOL_MANIFEST_INSTRUCTIONS).toBe(instructions);
    expect(MCP_SERVER_INFO).toEqual({ name: info?.name, version: info?.version });
    expect(MCP_TOOL_MANIFEST.map((t) => t.name)).toEqual([
      "get_code_session",
      "get_conversation",
      "list_code_projects",
      "list_recent_conversations",
      "memory_recall",
      "memory_resolve",
      "memory_search",
      "search_conversations",
      "session_summary",
    ]);
  });
});
